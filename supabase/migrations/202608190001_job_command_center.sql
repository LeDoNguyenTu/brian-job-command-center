create or replace function private.is_app_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.app_admins
    where email = lower(coalesce((select auth.jwt())->>'email', ''))
      and (user_id is null or user_id = (select auth.uid()))
  );
$$;

revoke all on function private.is_app_admin() from public;
grant execute on function private.is_app_admin() to authenticated, service_role;

create or replace function private.link_admin_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.app_admins
  set user_id = new.id,
      linked_at = now()
  where email = lower(new.email)
    and (user_id is null or user_id = new.id);
  return new;
end;
$$;

revoke all on function private.link_admin_user() from public;

create trigger link_admin_user_after_auth_change
after insert or update of email on auth.users
for each row execute function private.link_admin_user();

create or replace function public.is_current_admin()
returns boolean
language sql
stable
security invoker
set search_path = ''
as $$
  select private.is_app_admin();
$$;

revoke all on function public.is_current_admin() from public, anon;
grant execute on function public.is_current_admin() to authenticated;

create or replace function public.store_notion_token(token_value text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  existing_id uuid;
begin
  if not private.is_app_admin() then
    raise exception 'Not authorized' using errcode = '42501';
  end if;

  if token_value is null or char_length(trim(token_value)) < 20 or char_length(token_value) > 512 then
    raise exception 'Invalid Notion integration token';
  end if;

  select id into existing_id
  from vault.secrets
  where name = 'brian_notion_token'
  limit 1;

  if existing_id is null then
    perform vault.create_secret(trim(token_value), 'brian_notion_token', 'Brian Job Command Center Notion integration');
  else
    perform vault.update_secret(existing_id, trim(token_value), 'brian_notion_token', 'Brian Job Command Center Notion integration');
  end if;

  update public.app_settings
  set notion_connected = true,
      last_sync_status = 'Ready to sync',
      last_sync_message = 'Notion connection saved securely in Supabase Vault.',
      updated_at = now()
  where id = 1;
end;
$$;

revoke all on function public.store_notion_token(text) from public, anon;
grant execute on function public.store_notion_token(text) to authenticated;

create or replace function public.read_notion_token_for_service()
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  token_value text;
begin
  if coalesce((select auth.jwt())->>'role', '') <> 'service_role' then
    raise exception 'Service role required' using errcode = '42501';
  end if;

  select decrypted_secret into token_value
  from vault.decrypted_secrets
  where name = 'brian_notion_token'
  limit 1;

  return token_value;
end;
$$;

revoke all on function public.read_notion_token_for_service() from public, anon, authenticated;
grant execute on function public.read_notion_token_for_service() to service_role;

