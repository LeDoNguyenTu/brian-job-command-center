  location text not null default 'Singapore',
  work_mode text not null default 'Not specified',
  date_found date,
  matched_skills text[] not null default '{}',
  gaps_risks text,
  pipeline text not null default 'Discovered',
  approved_to_apply boolean not null default false,
  employment_type text,
  source text,
  job_url text,
  career_page text,
  ats_platform text,
  cv_version text,
  cv_status text,
  cover_letter_status text,
